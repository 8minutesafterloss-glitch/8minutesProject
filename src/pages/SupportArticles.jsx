function ArticleItem({ item, secIdx, itemIdx }) {
  const [open, setOpen] = useState(false);
  const labelKey = `articles_s${secIdx}_i${itemIdx}_label`;
  const metaKey = `articles_s${secIdx}_i${itemIdx}_meta`;
  const contentKey = `articles_s${secIdx}_i${itemIdx}_content`;
  return (
    <div className="bg-white rounded-xl border border-[#EDEDED] overflow-hidden transition-all hover:shadow-sm">
      <div
        onClick={() => setOpen(!open)}
        className="w-full p-4 flex items-center gap-3 text-right cursor-pointer"
      >
        <span className="flex-1 text-sm text-[#2D2A35] font-medium">
          <EditableCenterText contentKey={labelKey} fallback={item.label} as="span" category="מדריכים" />
        </span>
        <span className="text-xs text-[#8E8E93] whitespace-nowrap">
          <EditableCenterText contentKey={metaKey} fallback={item.meta} as="span" category="מדריכים" />
        </span>
        {open ? (
          <ChevronUp className="w-4 h-4 text-[#5E548E] flex-shrink-0" />
        ) : (
          <ChevronDown className="w-4 h-4 text-[#5E548E] flex-shrink-0" />
        )}
      </div>
      {open && (
        <div className="px-4 pb-4 pt-1 text-sm text-[#2D2A35] leading-relaxed whitespace-pre-line">
          <EditableCenterText contentKey={contentKey} fallback={item.content} as="div" category="מדריכים" />
        </div>
      )}
    </div>
  );
}

